def _from_tag(tag: str | None) -> MSO_LANGUAGE_ID:
    if tag is None:
        return MSO_LANGUAGE_ID.NONE
    for member, xml_tag in _LANGUAGE_TAGS.items():
        if xml_tag and xml_tag == tag:
            return member
    raise NotImplementedError(
        f"Font.language_id cannot map language tag {tag!r}; use Font.language "
        "to inspect or assign the preserved language tag"
    )


def _to_tag(value: object) -> str | None:
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(
            "Font.language_id accepts MSO_LANGUAGE_ID, an integer identifier or None, "
            f"got {type(value).__name__}"
        )
    try:
        member = MSO_LANGUAGE_ID(value)
    except ValueError:
        raise ValueError(f"Font.language_id has no supported identifier {value!r}") from None
    if member is MSO_LANGUAGE_ID.NONE:
        return None
    tag = _LANGUAGE_TAGS[member]
    if not tag:
        raise ValueError("Font.language_id cannot assign MSO_LANGUAGE_ID.MIXED; use Font.language")
    return tag


